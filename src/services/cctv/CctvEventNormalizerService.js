const CctvDevice = require('../../models/CctvDevice');
const CctvChannel = require('../../models/CctvChannel');
const CctvAdapterService = require('./CctvAdapterService');
const logger = require('../../config/logger');

// Valid standard event types specified in Prompt Section 4
const STANDARD_EVENT_TYPES = new Set([
  'motion.detected',
  'person.detected',
  'vehicle.detected',
  'face.detected',
  'line.crossed',
  'intrusion.detected',
  'loitering.detected',
  'crowd.detected',
  'abandoned.object',
  'removed.object',
  'camera.tampered',
  'camera.offline',
  'camera.online',
  'stream.failed',
  'recording.started',
  'recording.stopped',
  'recording.failed',
  'storage.full',
  'storage.failed',
  'network.failed',
  'authentication.failed',
  'access.denied',
  'access.granted',
  'door.opened',
  'door.forced',
  'ANPR.vehicle.detected',
  'fire.detected',
  'smoke.detected',
  'emergency.detected',
  'device.restarted',
  'firmware.updated',
  'channel.changed',
  'event.subscription.failed',
  'vendor.api.failed'
]);

class CctvEventNormalizerService {
  /**
   * Normalize an incoming hardware or webhook event into the standard internal format
   * @param {object} device - CctvDevice
   * @param {object|string} rawPayload - Inbound vendor webhook payload
   * @param {object} [options] - Channel number, headers, override eventType
   * @returns {Promise<object>} Normalized event payload
   */
  static async normalizeEvent(device, rawPayload, options = {}) {
    const adapter = CctvAdapterService.getAdapter(device);
    const parsed = adapter.parseWebhookPayload(rawPayload, options.headers || {});

    const channelNumber = options.channelNumber || parsed.channelNumber || 1;
    let channelDoc = null;
    if (['NVR', 'DVR', 'XVR'].includes(device.deviceType)) {
      channelDoc = await CctvChannel.findOne({
        deviceId: device._id,
        channelNumber: channelNumber
      });
    }

    const buildingId = (channelDoc && channelDoc.buildingId) || device.buildingId;
    const floorId = (channelDoc && channelDoc.floorId) || device.floorId;
    const unitOrSpaceId = (channelDoc && channelDoc.unitOrSpaceId) || device.unitOrSpaceId;
    const zoneId = (channelDoc && channelDoc.zoneId) || device.zoneId || 'COMMON_AREA';

    let eventType = options.eventType || parsed.eventType || 'motion.detected';
    if (!STANDARD_EVENT_TYPES.has(eventType)) {
      eventType = 'motion.detected';
    }

    const receivedTime = new Date();
    const eventTime = parsed.eventTime ? new Date(parsed.eventTime) : receivedTime;

    return {
      organisationId: device.organisationId,
      propertyId: device.propertyId,
      buildingId,
      floorId,
      unitOrSpaceId,
      zoneId,
      cameraId: device._id,
      recorderId: ['NVR', 'DVR', 'XVR'].includes(device.deviceType) ? device._id : null,
      channelId: channelDoc ? channelDoc._id : null,
      vendor: device.vendor,
      eventType,
      eventSource: parsed.eventSource || `${device.vendor}_EVENT`,
      severity: options.severity || parsed.severity || 'MEDIUM',
      title: options.title || parsed.title || `${device.name} - ${eventType}`,
      message: options.message || parsed.message || `Surveillance alert generated by ${device.name}`,
      eventTime,
      receivedTime,
      snapshotUrl: parsed.snapshotUrl || options.snapshotUrl || '',
      videoClipUrl: parsed.videoClipUrl || options.videoClipUrl || '',
      metadata: {
        ...parsed.metadata,
        ...(options.metadata || {}),
        cameraName: device.name,
        deviceType: device.deviceType,
        ipAddress: device.ipAddress
      },
      confidence: parsed.confidence || 0.95,
      status: 'NEW'
    };
  }
}

module.exports = {
  CctvEventNormalizerService,
  STANDARD_EVENT_TYPES
};
